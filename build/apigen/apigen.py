def load_overrides():
    if not os.path.exists(OVERRIDES):
        return {}
    with open(OVERRIDES, encoding='utf-8') as f:
        return yaml.safe_load(f) or {}


def build(check=False):
    overrides = load_overrides()
    names = overrides.get('names') or {}
    skips = overrides.get('skip') or {}
    covered_by = overrides.get('covered') or {}
    specs = load_specs()
    ops = all_operations(specs)
    hand = handwritten_functions()
    hand_paths = {}
    for fname, (folder, methods, paths, _) in hand.items():
        for p in paths:
            for m in methods:
                hand_paths.setdefault((m, p), []).append(fname)

    functions = OrderedDict()
    for op in ops:
        key = op.key
        npath = norm_path(op.full_path)
        if key in covered_by:
            op.status, op.function = 'handwritten', covered_by[key]
            continue
        hits = hand_paths.get((op.method, npath))
        if hits:
            op.status, op.function = 'handwritten', ', '.join(sorted(set(hits)))
            continue
        if key in skips:
            op.status, op.note = 'skipped', skips[key]
            continue
        if op.deprecated:
            op.status, op.note = 'deprecated', 'Deprecated by TOPdesk, not generated.'
            continue
        verb, noun, switch = derive(op)
        name = names.get(key) or '%s-Td%s' % (verb, noun)
        if isinstance(name, dict):
            switch = name.get('switch', switch)
            name = name['name']
        if name in hand:
            op.status, op.note = 'skipped', 'Name conflicts with hand-written %s; add an override.' % name
            print('CONFLICT %-60s -> %s (hand-written)' % (key, name))
            continue
        variant = build_variant(op, switch, overrides)
        if variant.body_kind == 'raw':
            op.status, op.note = 'skipped', 'Raw (non JSON, non multipart) request bodies are not supported by the generator.'
            continue
        fn = functions.get(name)
        if fn is None:
            fn = functions[name] = Function(name, AREAS[op.area][0])
        sig = set_signature(variant)
        clash = next((v for v in fn.variants if set_signature(v) == sig), None)
        if clash is not None:
            # Same parameters: PUT and PATCH aliases of the same action. Keep the PATCH (or the first one).
            if op.method == 'PATCH' and clash.op.method == 'PUT':
                fn.variants[fn.variants.index(clash)] = variant
                clash.op.status, clash.op.function, clash.op.note = 'generated', name, 'Same action as PATCH; the PATCH variant is used.'
                op.status, op.function = 'generated', name
            else:
                op.status, op.function, op.note = 'generated', name, 'Same action as %s %s, which is used.' % (clash.op.method, clash.op.path)
            continue
        fn.variants.append(variant)
        op.status, op.function = 'generated', name

    # write files
    existing = generated_files()
    written = set()
    changes = []
    for name, fn in functions.items():
        code = emit_function(fn, overrides)
        folder = os.path.join(FUNCTIONS, fn.folder)
        path = os.path.join(folder, name + '.ps1')
        old_path = existing.get(name)
        data = codecs.BOM_UTF8 + code.encode('utf-8')
        if old_path and os.path.abspath(old_path) != os.path.abspath(path):
            changes.append('move %s' % name)
            if not check:
                os.remove(old_path)
        current = open(path, 'rb').read() if os.path.exists(path) else None
        if current != data:
            changes.append(('update ' if current else 'create ') + name)
            if not check:
                os.makedirs(folder, exist_ok=True)
                with open(path, 'wb') as f:
                    f.write(data)
        written.add(name)
    for name, path in existing.items():
        if name not in written:
            changes.append('delete %s' % name)
            if not check:
                os.remove(path)
    manifest_change = update_manifest(check, set(written) | set(hand))
    if manifest_change:
        changes.append(manifest_change)
    report = coverage_report(specs, ops, hand, overrides.get('notes') or {})
    current = open(COVERAGE, encoding='utf-8').read() if os.path.exists(COVERAGE) else None
    if current != report:
        changes.append('update docs/api-coverage.md')
        if not check:
            with open(COVERAGE, 'w', encoding='utf-8') as f:
                f.write(report)
    counts = {}
    for op in ops:
        counts[op.status] = counts.get(op.status, 0) + 1
    print('operations: %d  %s' % (len(ops), '  '.join('%s=%d' % kv for kv in sorted(counts.items()))))
    print('generated functions: %d, file changes: %d' % (len(functions), len(changes)))
    if check:
        for c in changes:
            print('  ' + c)
    return changes


def update_manifest(check, names):
    """Rewrites FunctionsToExport in TOPdeskPS.psd1 so it lists every file in functions/."""
    path = os.path.join(MODULE, 'TOPdeskPS.psd1')
    raw = open(path, 'rb').read()
    bom = raw.startswith(codecs.BOM_UTF8)
    text = raw.decode('utf-8-sig')
    on_disk = set()
    for folder, _, files in os.walk(FUNCTIONS):
        on_disk.update(f[:-4] for f in files if f.endswith('.ps1'))
    if not check:
        names = on_disk
    else:
        names = (names | on_disk)
    line = 'FunctionsToExport = @(%s)' % ','.join("'%s'" % n for n in sorted(names, key=str.lower))
    new = re.sub(r'FunctionsToExport\s*=\s*@\([^)]*\)', lambda m: line, text, count=1)
    if new == text:
        return None
    if not check:
        with open(path, 'wb') as f:
            f.write((codecs.BOM_UTF8 if bom else b'') + new.encode('utf-8'))
    return 'update TOPdeskPS.psd1 FunctionsToExport'


def coverage_report(specs, ops, hand, notes):
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    out = ['# TOPdesk API coverage', '',
           'This file is generated by `python3 build/apigen/apigen.py generate`. It compares TOPdeskPS with the official',
           'TOPdesk API specifications from [developers.topdesk.com](https://developers.topdesk.com/explorer/).', '',
           '| Area | Spec version | Operations | Hand-written | Generated | Deprecated | Skipped |',
           '| --- | --- | ---: | ---: | ---: | ---: | ---: |']
    totals = [0, 0, 0, 0, 0]
    for spec in specs:
        aops = [o for o in ops if o.area == spec.key]
        row = [len(aops)] + [sum(1 for o in aops if o.status == s) for s in ('handwritten', 'generated', 'deprecated', 'skipped')]
        totals = [a + b for a, b in zip(totals, row)]
        out.append('| %s | %s | %d | %d | %d | %d | %d |' % ((AREAS[spec.key][1], (lock.get(spec.key) or {}).get('version', '?')) + tuple(row)))
    out.append('| **Total** | | %d | %d | %d | %d | %d |' % tuple(totals))
    out.append('')

    # hand-written functions calling endpoints that are gone or deprecated
    spec_paths = {}
    for o in ops:
        spec_paths.setdefault(norm_path(o.full_path), []).append(o)
    out += ['## Hand-written functions and the current API', '']
    rows = []
    for fname in sorted(hand):
        folder, methods, paths, _ = hand[fname]
        for p in sorted(paths):
            matches = spec_paths.get(p)
            if not matches:
                # A {} in a module path can stand for a literal segment, for example login/{UserType}.
                pattern = re.compile('^' + re.escape(p).replace(re.escape('{}'), '[^/]+') + '$')
                matches = [o for sp, lst in spec_paths.items() if pattern.match(sp) for o in lst]
            note = (notes.get(fname) or '').replace('|', '/')
            if not matches:
                rows.append('| %s | `%s` | Not in the current specification | %s |' % (fname, p, note))
            else:
                dep = [o for o in matches if o.deprecated and o.method in methods]
                if dep:
                    rows.append('| %s | `%s` | Deprecated: %s | %s |' % (fname, p, dep[0].summary.replace('|', '/'), note))
    if rows:
        out += ['| Function | Endpoint | Status | Notes |', '| --- | --- | --- | --- |'] + rows
    else:
        out.append('All endpoints used by hand-written functions are in the current specifications and not deprecated.')
    out.append('')

    for spec in specs:
        aops = [o for o in ops if o.area == spec.key]
        out += ['## %s' % AREAS[spec.key][1], '', '| Method | Endpoint | Function | Notes |', '| --- | --- | --- | --- |']
        for o in sorted(aops, key=lambda o: (o.full_path.lower(), o.method)):
            fn = o.function or ''
            note = o.note or ('Deprecated' if o.status == 'deprecated' else '')
            out.append('| %s | `%s` | %s | %s |' % (o.method, o.full_path, fn, note.replace('|', '/')))
        out.append('')
    return '\n'.join(out)


def main(argv):
    cmd = argv[1] if len(argv) > 1 else 'generate'
    if cmd == 'fetch':
        cmd_fetch()
    elif cmd == 'generate':
        build(check=False)
    elif cmd == 'check':
        changes = build(check=True)
        sys.exit(1 if changes else 0)
    else:
        print(__doc__)
        sys.exit(2)


if __name__ == '__main__':
    main(sys.argv)
