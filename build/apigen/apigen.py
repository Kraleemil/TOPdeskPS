def all_operations(specs):
    ops = []
    for spec in specs:
        for path, item in (spec.doc.get('paths') or {}).items():
            item = spec.res(item)
            for method, op in item.items():
                if method in ('get', 'post', 'put', 'patch', 'delete') and isinstance(op, dict):
                    ops.append(Operation(spec, method, path, op, item))
    return ops


def norm_path(p):
    p = p.split('?')[0]
    p = re.sub(r'\$\((?:[^()]|\([^()]*\))*\)', '{}', p)
    p = re.sub(r'\$[A-Za-z_.]+', '{}', p)
    p = re.sub(r'\{[^}]*\}', '{}', p)
    return p.rstrip('/').lower()


def trim_uri(text):
    text = text.rstrip('.,;')
    while text.endswith(')') and text.count('(') < text.count(')'):
        text = text[:-1].rstrip('.,;')
    return text


def handwritten_functions():
    """Scans hand-written functions: name -> (folder, set of methods, set of normalized paths, file)."""
    result = {}
    for folder, _, files in os.walk(FUNCTIONS):
        for f in files:
            if not f.endswith('.ps1'):
                continue
            path = os.path.join(folder, f)
            with open(path, encoding='utf-8-sig') as fh:
                text = fh.read()
            if text.startswith(GENERATED_MARKER):
                continue
            code = re.sub(r'(?s)<#.*?#>', '', text)
            code = re.sub(r'(?m)^\s*#.*$', '', code)
            paths = {norm_path(trim_uri(m)) for m in re.findall(r'(/(?:tas/api|services)/[^"\' \n`]*)', code)}
            methods = {m.upper() for m in re.findall(r"(?i)method\s*['\"]?\s*[=:]?\s*['\"]?(get|post|put|patch|delete)\b", text)} or {'GET'}
            result[f[:-4]] = (os.path.relpath(folder, FUNCTIONS), methods, paths, path)
    return result


def generated_files():
    files = {}
    for folder, _, names in os.walk(FUNCTIONS):
        for f in names:
            if f.endswith('.ps1'):
                path = os.path.join(folder, f)
                with open(path, encoding='utf-8-sig') as fh:
                    if fh.read(len(GENERATED_MARKER)) == GENERATED_MARKER:
                        files[f[:-4]] = path
    return files


