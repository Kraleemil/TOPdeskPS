class Param:
    def __init__(self, name, kind, api_name, ptype='string', help_text='', required=False, enum=None,
                 ref_object=False, default=None):
        self.name = name              # PowerShell parameter name
        self.kind = kind              # path | query | body | form | file | switch | special
        self.api_name = api_name      # name in the API
        self.ptype = ptype            # PowerShell type
        self.help = help_text
        self.required = required
        self.enum = enum
        self.ref_object = ref_object  # body property that is an {id} reference
        self.default = default


class Operation:
    def __init__(self, spec, method, path, op, path_item):
        self.spec = spec
        self.area = spec.key
        self.method = method.upper()
        self.path = path
        self.full_path = spec.base + path
        self.op = op
        self.summary = first_sentence(op.get('summary') or op.get('description') or '')
        self.description = clean_text(op.get('description') or op.get('summary') or '')
        self.deprecated = bool(op.get('deprecated')) or bool(re.match(r'\s*(\*\*|```)?\s*deprecat', op.get('description') or '', re.I)) \
            or 'this endpoint has been deprecated' in (op.get('description') or '').lower() \
            or 'this endpoint is deprecated' in (op.get('description') or '').lower() \
            or (op.get('summary') or '').lower().find('(deprecated)') >= 0
        self.parameters = [spec.res(p) for p in (path_item.get('parameters') or []) + (op.get('parameters') or [])]
        self.key = '%s %s' % (self.method, self.full_path)
        self.function = None
        self.status = None          # handwritten | generated | skipped | deprecated
        self.note = ''

    # request body ------------------------------------------------------
    def body_info(self):
        """Returns (content_type, schema, form_params) for the request."""
        spec = self.spec
        if spec.v3:
            rb = spec.res(self.op.get('requestBody') or {})
            content = rb.get('content') or {}
            if not content:
                return None, None, []
            ctype = next((c for c in content if 'multipart' in c), None) or next(iter(content))
            schema = spec.res(content[ctype].get('schema') or {})
            if 'multipart' in ctype or 'form-urlencoded' in ctype:
                form = []
                for k, v in spec.schema_props(schema).items():
                    form.append((k, v, k in (schema.get('required') or [])))
                return ctype, schema, form
            return ctype, schema, []
        consumes = self.op.get('consumes') or spec.doc.get('consumes') or ['application/json']
        body = [p for p in self.parameters if p.get('in') == 'body']
        form = [p for p in self.parameters if p.get('in') == 'formData']
        if form:
            ctype = next((c for c in consumes if 'multipart' in c), 'multipart/form-data')
            return ctype, None, [(p['name'], p, p.get('required', False)) for p in form]
        if body:
            return consumes[0], spec.res(body[0].get('schema') or {}), []
        return None, None, []

    def response_info(self):
        """Returns (media types, schema) of the success response."""
        spec = self.spec
        responses = self.op.get('responses') or {}
        for code in ('200', 200, '206', 206, '201', 201, 'default'):
            r = responses.get(code)
            if r is None:
                continue
            r = spec.res(r)
            if spec.v3:
                content = r.get('content') or {}
                if not content:
                    return [], None
                types = list(content)
                pick = next((t for t in types if 'json' in t and 'v1' not in t), types[0])
                return types, spec.res(content[pick].get('schema') or {})
            produces = self.op.get('produces') or spec.doc.get('produces') or ['application/json']
            return produces, spec.res(r.get('schema') or {})
        return [], None


def load_specs():
    specs = []
    for key in AREAS:
        files = [f for f in os.listdir(SPECS) if f.startswith(key + '.')] if os.path.isdir(SPECS) else []
        if files:
            specs.append(Spec(key, os.path.join(SPECS, files[0])))
