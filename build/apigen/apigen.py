def derive(op):
    """Returns (verb, noun, switch, variant label) for an operation."""
    path = op.path
    if op.area == 'assets':
        path = re.sub(r'^/assetmgmt', '', path)
    segs = [s for s in path.strip('/').split('/') if s]
    prefix = ''
    if segs and segs[0] == 'requester':
        prefix = 'Requester'
        segs = segs[1:]
    if op.area == 'change' and segs and segs[0].startswith('requester'):
        prefix = 'Requester'
        segs[0] = segs[0][len('requester'):]
        segs[0] = segs[0][0].lower() + segs[0][1:]
    literals = []
    variant = []
    last_literal_index = -1
    i = 0
    while i < len(segs):
        s = segs[i]
        if s.startswith('{'):
            variant.append(s.strip('{}'))
        elif s in LABELS and i + 1 < len(segs) and segs[i + 1].startswith('{'):
            if s == 'number':
                variant.append('#number')
        else:
            literals.append(s)
            last_literal_index = i
        i += 1
    ends_with_param = bool(segs) and segs[-1].startswith('{')
    action = None
    if literals and not ends_with_param and op.method != 'GET' and literals[-1] in ACTIONS and len(literals) > 1:
        action = literals.pop()
    if literals and literals[-1] == 'download' and op.method == 'GET':
        action = literals.pop()
    if action is None and op.method == 'GET' and re.match(r'(?i)download', op.summary or ''):
        action = 'download'
    parts = []
    for s in literals:
        part = noun_part(s, op.area)
        if part:
            if parts and part.startswith(parts[-1]):
                parts[-1] = part
            elif parts and parts[-1].endswith(part):
                continue
            else:
                parts.append(part)
    noun = prefix + ''.join(parts)
    switch = None
    if action:
        verb, suffix, switch = ACTIONS[action]
        noun += suffix
    elif op.method == 'GET':
        verb = 'Get'
    elif op.method == 'DELETE':
        verb = 'Remove'
    elif op.method in ('PUT', 'PATCH'):
        verb = 'Set'
    else:  # POST
        ctype, _, form = op.body_info()
        if ctype and ('multipart' in ctype or 'octet-stream' in ctype):
            verb = 'Send'
        elif re.match(r'(?i)(create|add|register|new)\b', op.summary or ''):
            verb = 'New'
        elif re.match(r'(?i)link\b', op.summary or ''):
            verb = 'Add'
        elif ends_with_param:
            verb = 'Set'
        else:
            verb = 'New'
    if op.area == 'assets' and not noun.startswith('Asset') and noun:
        noun = 'Asset' + noun
    if op.area == 'visitors' and noun.startswith(('Badge', 'CarPark', 'IdentificationType')):
        noun = 'Visitor' + noun
    return verb, noun, switch


def param_ps_name(api_name, kind, taken):
    if kind == 'path' and api_name.lower() in ('id', 'identifier'):
        name = 'Id'
    else:
        name = pascal(api_name) or 'Value'
    if name.lower() in RESERVED_NAMES:
        name += 'Value'
    return name


def schema_ps_type(spec, s):
    s = spec.res(s or {})
    t = s.get('type')
    fmt = s.get('format')
    if t == 'array':
        it = spec.res(s.get('items') or {})
        inner = schema_ps_type(spec, it)
        if inner in ('string', 'int', 'long', 'double'):
            return inner + '[]'
        return None
    if t == 'integer':
        return 'long' if fmt == 'int64' else 'int'
    if t == 'number':
        return 'double'
    if t == 'boolean':
        return 'switch'
    if t == 'string':
        if fmt == 'binary':
            return 'file'
        return 'string'
    if t is None and not s:
        return 'string'
    return None


def enum_values(spec, s):
    s = spec.res(s or {})
    if s.get('type') == 'array':
        s = spec.res(s.get('items') or {})
    vals = s.get('enum')
    if vals and len(vals) <= 40 and all(isinstance(v, str) and "'" not in v for v in vals):
        return vals
    return None


def is_ref_object(spec, s):
    props = spec.schema_props(s)
    keys = set(props)
    return bool(keys) and 'id' in keys and keys <= {'id', 'name', 'type', 'dynamicName', 'number', 'groupName', 'code', 'tasLoginName'}


