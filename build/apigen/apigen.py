def http_get(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'TOPdeskPS-apigen'})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def version_key(v):
    return [int(x) if x.isdigit() else x for x in re.split(r'[.-]', v)]


def explorer_config():
    """Reads the explorer configuration (pages and spec versions) from the site's JS bundle."""
    html = http_get(SITE + '/explorer/').decode('utf-8', 'replace')
    main = re.search(r'src="(/js/explorer[^"]*\.js)"', html).group(1)
    js = http_get(SITE + main).decode('utf-8', 'replace')
    chunks = set(re.findall(r'(\d+):"[0-9a-f]{16,}"', js))
    pages = {}
    for chunk in sorted(chunks):
        text = http_get('%s/js/%s.js' % (SITE, chunk)).decode('utf-8', 'replace')
        for m in re.finditer(r'"([a-z-]+)":\{(?:"isTos":(?:true|false),)?"title":"([^"]+)","versions":(\[.*?\])\}', text):
            try:
                pages[m.group(1)] = {'title': m.group(2), 'versions': json.loads(m.group(3))}
            except ValueError:
                pass
    if not pages:
        raise SystemExit('Could not find the explorer configuration on %s' % SITE)
    return pages


def pick_version(key, versions):
    if key == 'knowledge-base':
        after = [v for v in versions if 'after' in v['key']]
        return after[0] if after else versions[0]
    numeric = [v for v in versions if re.match(r'^\d+(\.\d+)*$', v['key'])]
    if numeric:
        return max(numeric, key=lambda v: version_key(v['key']))
    return versions[0]


def cmd_fetch():
    pages = explorer_config()
    os.makedirs(SPECS, exist_ok=True)
    lock = OrderedDict()
    for key in AREAS:
        if key not in pages:
            print('WARNING: explorer has no page %s' % key)
            continue
        v = pick_version(key, pages[key]['versions'])
        data = http_get('%s/swagger/%s' % (SITE, v['fileName']))
        ext = os.path.splitext(v['fileName'])[1]
        for old in os.listdir(SPECS):
            if old.startswith(key + '.'):
                os.remove(os.path.join(SPECS, old))
        with open(os.path.join(SPECS, key + ext), 'wb') as f:
            f.write(data)
        lock[key] = {'title': pages[key]['title'], 'version': v['key'], 'file': v['fileName']}
        print('%-24s %-12s %s' % (key, v['key'], v['fileName']))
    for key in pages:
        if key not in AREAS:
            print('NOTE: explorer page %s (%s) is not in AREAS and was not downloaded' % (key, pages[key]['title']))
    with open(LOCK, 'w') as f:
        json.dump(lock, f, indent=2)
        f.write('\n')


class Spec:
    def __init__(self, key, path):
        self.key = key
        with open(path, encoding='utf-8') as f:
            self.doc = yaml.safe_load(f) if path.endswith(('.yaml', '.yml')) else json.load(f)
        d = self.doc
        self.v3 = 'openapi' in d
        base = ''
        if self.v3 and d.get('servers'):
            base = re.sub(r'^[a-z]+://[^/]*', '', d['servers'][0].get('url', ''))
        elif d.get('basePath'):
            base = d['basePath']
        self.base = base.rstrip('/')

    def res(self, x, depth=0):
        if isinstance(x, dict) and '$ref' in x and depth < 30:
            y = self.doc
            for k in x['$ref'].lstrip('#/').split('/'):
                k = k.replace('~1', '/').replace('~0', '~')
                y = y.get(k, {}) if isinstance(y, dict) else {}
            return self.res(y, depth + 1)
        return x

    def schema_props(self, s, depth=0):
        """Top level properties of a schema, following allOf."""
        s = self.res(s)
        props = OrderedDict()
        if depth > 10 or not isinstance(s, dict):
            return props
        for part in s.get('allOf', []):
            props.update(self.schema_props(part, depth + 1))
        for k, v in (s.get('properties') or {}).items():
            props[k] = self.res(v)
        return props


# --------------------------------------------------------------------------- text helpers
def clean_text(text, limit=1500):
    if not text:
        return ''
    text = str(text)
    text = re.sub(r'(?im)^\s*\|.*\|\s*$', '', text)                  # markdown tables
    text = re.sub(r'<br\s*/?>', '\n', text)
    text = re.sub(r'</?(p|ul|ol|div)[^>]*>', '\n', text)
    text = re.sub(r'<li[^>]*>', '\n- ', text)
    text = re.sub(r'<[^>]+>', '', text)
    text = text.replace('&lt;', '<').replace('&gt;', '>').replace('&amp;', '&').replace('&quot;', '"').replace('&nbsp;', ' ')
    text = text.replace('```', '').replace('**', '').replace('__', '')
    text = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', r'\1 (\2)', text)
    text = text.replace('<#', '< #').replace('#>', '# >').replace('`', "'")
    text = text.replace('\u2018', "'").replace('\u2019', "'").replace('\u201c', '"').replace('\u201d', '"')
    # A line starting with a dot could be read as a comment-based help keyword (.PARAMETER, .LINK, ...).
    lines = [re.sub(r'^\.+\s*', '', l.strip()) for l in text.splitlines()]
    out, blank = [], False
    for l in lines:
        if not l:
            if out and not blank:
                out.append('')
            blank = True
            continue
        if re.match(r'^(-+|[-| :]+)$', l):
            continue
        out.append(l)
        blank = False
    text = '\n'.join(out).strip()
    if len(text) > limit:
        cut = text[:limit]
        text = cut[:cut.rfind(' ')] + ' ...' if ' ' in cut else cut
    return text


def first_sentence(text):
    text = clean_text(text, 400).split('\n')[0].strip()
    return text


def pascal(name):
    name = name.lstrip('$')
    parts = re.split(r'[^A-Za-z0-9]+', name)
    out = ''
    for p in parts:
        if p:
            out += p[0].upper() + p[1:]
    if out and out[0].isdigit():
        out = 'N' + out
    return out


def singular(word):
    if word in NO_SINGULAR:
        return word
    m = re.match(r'^(.*?)([A-Z]?[a-z0-9]+)$', word)
    head, last = (m.group(1), m.group(2)) if m else ('', word)
    low = last.lower()
    if low in NO_SINGULAR or low.endswith(('ss', 'us', 'is')):
        return word
    if low.endswith('ies'):
        last = last[:-3] + 'y'
    elif low.endswith(('sses', 'ches', 'shes', 'xes', 'statuses')):
        last = last[:-2]
    elif low.endswith('s'):
        last = last[:-1]
    return head + last


def noun_part(seg, area=None):
    if seg == 'services' and area == 'services':
        return 'CatalogService'
    if seg in SEGMENT_NOUNS:
        return SEGMENT_NOUNS[seg]
    return pascal(singular(seg))


def ps_quote(text):
    return "'" + str(text).replace("'", "''") + "'"


